const DICTS: Record<Lang, Dict> = { tr, en, it };

const STORAGE_KEY = 'app_language';

type LanguageState = {
  lang: Lang;
  setLang: (lang: Lang) => Promise<void>;
  t: (key: string) => string;
};

const LanguageContext = createContext<LanguageState | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const { user, updateUser } = useAuth();
  const [lang, setLangState] = useState<Lang>('tr');

  // Açılışta: giriş yapılmışsa kullanıcının kayıtlı dili, yoksa cihazda
  // önceden seçilmiş dil (login/register ekranları için) kullanılır.
  useEffect(() => {
    if (user?.language) {
      setLangState(user.language as Lang);
      return;
    }
    // '' -> cihazda daha önce hiç seçim yapılmamış (ilk ziyaret). Böyle bir
    // durumda IP'nin ülkesine göre bir öneri sorulur (İtalya->it, Türkiye->tr,
    // diğer tüm ülkeler->en); ağ hatası olursa sessizce 'tr' varsayılanında
    // kalınır. Daha önce açıkça seçim yapılmışsa (tr/en/it) o hep kullanılır,
    // bir daha IP'ye bakılmaz.
    storage.getItem<string>(STORAGE_KEY, '').then((v) => {
      if (v === 'en' || v === 'it' || v === 'tr') {
        setLangState(v);
        return;
      }
      api.geoLang().then((res) => {
        if (res?.lang === 'en' || res?.lang === 'it' || res?.lang === 'tr') {
          setLangState(res.lang);
          storage.setItem(STORAGE_KEY, res.lang);
        }
      }).catch(() => {
        // varsayılan 'tr' state'i kalır
      });
    });
  }, [user?.language]);

  const setLang = useCallback(async (next: Lang) => {
    setLangState(next); // anında yansısın diye önce local state
    await storage.setItem(STORAGE_KEY, next);
    if (user) {
      try {
        await updateUser({ language: next } as any);
      } catch {
        // Sunucuya yazılamasa bile ekran anında güncellendi; bir sonraki
        // profil senkronizasyonunda tekrar denenecek.
      }
    }
  }, [user, updateUser]);

  const t = useCallback((key: string): string => {
    const [ns, k] = key.split('.');
    const dict = DICTS[lang];
    return dict?.[ns]?.[k] ?? DICTS.tr?.[ns]?.[k] ?? key;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageState {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
